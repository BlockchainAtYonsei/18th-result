import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Run contracts:compile first. Only ABI data is copied into the runtime bundle.
for (const name of ['MoaFactory', 'MoaAccount']) {
  const artifact = JSON.parse(readFileSync(new URL(`../../contracts/artifacts/contracts/${name}.sol/${name}.json`, import.meta.url), 'utf8'));
  const content = `// Generated by scripts/sync-contract-abi.mjs; do not edit.\nexport const ${name}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  const destination = fileURLToPath(new URL(`../src/blockchain/abi/${name}.ts`, import.meta.url));
  if (process.argv.includes('--check')) {
    if (readFileSync(destination, 'utf8') !== content) throw new Error(`${name} ABI drift; run abi:sync`);
  } else writeFileSync(destination, content);
}
